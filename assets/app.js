  /* ---------- theme ---------- */
  var KEY = "psp-theme";
  function applyTheme(t) {
    if (t === "dark") document.documentElement.setAttribute("data-theme", "dark");
    else document.documentElement.removeAttribute("data-theme");
    var b = document.getElementById("themeToggle");
    if (b) b.textContent = t === "dark" ? "light" : "dark";
  }
  var saved = null;
  try { saved = localStorage.getItem(KEY); } catch (e) { saved = null; }
  if (!saved) {
    saved = (window.matchMedia &&
             window.matchMedia("(prefers-color-scheme: dark)").matches) ? "dark" : "light";
  }
  applyTheme(saved);

  /* ---------- helpers ---------- */
  function el(tag, cls, txt) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (txt !== undefined && txt !== null) e.textContent = txt;
    return e;
  }
  function num(v) { return v === null || v === undefined || v === "" ? "—" : v; }
  function fmtEdge(v) { return (v > 0 ? "+" : "") + v.toFixed(2) + "%"; }
  function money(v, dp) { return "$" + Number(v).toFixed(dp === undefined ? 2 : dp); }
  function table(host, caption, heads, rows) {
    var t = el("table");
    if (caption) t.appendChild(el("caption", null, caption));
    var thead = el("thead"), tr = el("tr");
    heads.forEach(function (h) {
      var th = el("th", h[1] || "", h[0]);
      tr.appendChild(th);
    });
    thead.appendChild(tr); t.appendChild(thead);
    var tb = el("tbody");
    rows.forEach(function (r) {
      var row = el("tr");
      if (r.rowClass) row.className = r.rowClass;
      r.cells.forEach(function (c) {
        var v = (typeof c === "object") ? c : { t: c };
        var td = el("td", v.c || "", v.t);
        if (v.style) td.setAttribute("style", v.style);
        row.appendChild(td);
      });
      tb.appendChild(row);
    });
    t.appendChild(tb);
    if (host) { host.innerHTML = ""; host.appendChild(t); }
    return t;
  }

  /* ---------- ledger maths ---------- */
  function totals(L) {
    var bets = (L && L.bets) || [];
    var settled = bets.filter(function (b) { return b.result && b.result !== "pending"; });
    var staked = 0, ret = 0, profit = 0, wins = 0, losses = 0, pushes = 0, clvBeats = 0, clvN = 0;
    var oddsSum = 0, oddsN = 0;
    settled.forEach(function (b) {
      var st = Number(b.stake_nz) || 0;
      staked += st;
      profit += Number(b.profit_nz) || 0;
      ret += st + (Number(b.profit_nz) || 0);
      if (b.result === "win") wins++;
      else if (b.result === "loss") losses++;
      else pushes++;
      if (b.closing_price_nz) {
        clvN++;
        if (Number(b.price_taken) > Number(b.closing_price_nz)) clvBeats++;
      }
    });
    bets.forEach(function (b) {
      if (b.price_taken) { oddsSum += Number(b.price_taken); oddsN++; }
    });
    var decided = wins + losses;
    return {
      betCount: bets.length, settledCount: settled.length,
      staked: staked, returned: ret, profit: profit,
      wins: wins, losses: losses, pushes: pushes,
      hitRate: decided ? (wins / decided) * 100 : null,
      avgPrice: oddsN ? oddsSum / oddsN : null,
      clvBeats: clvBeats, clvN: clvN,
      clvRate: clvN ? (clvBeats / clvN) * 100 : null,
      bankroll: (Number(L && L.starting_bankroll_nz) || 0) + profit
    };
  }

