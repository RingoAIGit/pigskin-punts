  function renderBankrollChart(id, L) {
    var host = document.getElementById(id);
    if (!host) return;
    var bets = ((L && L.bets) || []).filter(function (b) { return b.result && b.result !== "pending"; });
    var start = Number(L.starting_bankroll_nz) || 0;
    var pts = [{ label: "start", v: start }];
    var run = start;
    bets.forEach(function (b, i) {
      run += Number(b.profit_nz) || 0;
      pts.push({ label: "bet " + (i + 1), v: run });
    });
    var W = 600, H = 150, PAD = 34;
    var vals = pts.map(function (p) { return p.v; });
    var lo = Math.min.apply(null, vals.concat([start])), hi = Math.max.apply(null, vals.concat([start]));
    if (hi - lo < 2) { lo -= 3; hi += 3; }
    var pad = (hi - lo) * 0.15; lo -= pad; hi += pad;
    var x = function (i) { return PAD + (i * (W - PAD * 2) / Math.max(pts.length - 1, 1)); };
    var y = function (v) { return H - PAD + 6 - ((v - lo) / (hi - lo)) * (H - PAD * 2); };
    var d = pts.map(function (p, i) { return (i ? "L" : "M") + x(i).toFixed(1) + " " + y(p.v).toFixed(1); }).join(" ");
    var startY = y(start).toFixed(1);
    var svg = '<svg viewBox="0 0 ' + W + " " + H + '" role="img" aria-label="Bankroll over time">' +
      '<line x1="' + PAD + '" y1="' + startY + '" x2="' + (W - PAD) + '" y2="' + startY +
        '" stroke="currentColor" stroke-dasharray="4 4" opacity="0.4" stroke-width="1"/>' +
      '<path d="' + d + '" fill="none" stroke="var(--ringo)" stroke-width="2.5" stroke-linejoin="round" stroke-linecap="round"/>' +
      pts.map(function (p, i) {
        return '<circle cx="' + x(i).toFixed(1) + '" cy="' + y(p.v).toFixed(1) + '" r="3" fill="var(--ringo)"/>';
      }).join("") +
      '<text x="' + PAD + '" y="16" font-size="11" fill="currentColor" opacity="0.65">start ' + money(start, 0) + "</text>" +
      '<text x="' + (W - PAD) + '" y="16" font-size="11" fill="currentColor" opacity="0.65" text-anchor="end">now ' + money(run, 0) + "</text>" +
      "</svg>";
    host.innerHTML = svg + (bets.length ? "" :
      '<p class="empty-note">Flat, and correct — no bet has been settled yet.</p>');
  }

