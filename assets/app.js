/* Pig Skin Punts — client-side render for the data modules.
   All numbers come from assets/data/week01.json (generated by
   build_week01_data.py) so nothing on the site is hand-typed.
   No IntersectionObserver, no dynamic viewport units — iOS Safari safe. */
(function () {
  "use strict";

  /* ---------- theme ---------- */
  var KEY = "psp-theme";
  function applyTheme(t) {
    if (t === "dark") {
      document.documentElement.setAttribute("data-theme", "dark");
    } else {
      document.documentElement.removeAttribute("data-theme");
    }
    var b = document.getElementById("themeToggle");
    if (b) b.textContent = t === "dark" ? "light" : "dark";
  }
  var saved = null;
  try { saved = localStorage.getItem(KEY); } catch (e) { saved = null; }
  if (!saved) {
    saved = (window.matchMedia &&
             window.matchMedia("(prefers-color-scheme: dark)").matches) ? "dark" : "light";
  }
  applyTheme(saved);
  document.addEventListener("DOMContentLoaded", function () {
    var b = document.getElementById("themeToggle");
    if (!b) return;
    b.addEventListener("click", function () {
      var next = document.documentElement.getAttribute("data-theme") === "dark"
        ? "light" : "dark";
      try { localStorage.setItem(KEY, next); } catch (e) {}
      applyTheme(next);
    });
  });

  /* ---------- nav ---------- */
  document.addEventListener("DOMContentLoaded", function () {
    var here = location.pathname.split("/").pop() || "index.html";
    var links = document.querySelectorAll("nav.tabs a[href]");
    for (var i = 0; i < links.length; i++) {
      if (links[i].getAttribute("href") === here) {
        links[i].setAttribute("aria-current", "page");
      }
    }
  });

  /* ---------- helpers ---------- */
  function el(tag, cls, txt) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (txt !== undefined && txt !== null) e.textContent = txt;
    return e;
  }
  function fmtEdge(v) {
    return (v > 0 ? "+" : "") + v.toFixed(2) + "%";
  }
  function money(v, dp) {
    return "$" + Number(v).toFixed(dp === undefined ? 2 : dp);
  }

  /* ---------- the gate bar ---------- */
  var GATE_MIN = -12, GATE_MAX = 6, GATE_AT = 4;
  var SPAN = GATE_MAX - GATE_MIN;
  function pct(v) { return ((v - GATE_MIN) / SPAN) * 100; }

  function gateRow(row) {
    var wrap = el("div", "gate-row");

    var who = el("div", "who");
    who.appendChild(document.createTextNode(row.side));
    var sub = el("small", null, row.sub || "");
    who.appendChild(sub);
    wrap.appendChild(who);

    var gate = el("div", "gate");
    var isPos = row.edge >= 0;
    var bar = el("div", "bar" + (row.edge >= GATE_AT ? " qualify" : ""));
    var left = isPos ? pct(0) : pct(row.edge);
    var right = isPos ? pct(row.edge) : pct(0);
    bar.style.left = left + "%";
    bar.style.width = Math.max(right - left, 0.4) + "%";
    gate.appendChild(bar);

    var zeroLine = el("div", "zero");
    zeroLine.style.left = pct(0) + "%";
    gate.appendChild(zeroLine);

    var th = el("div", "threshold");
    th.style.left = pct(GATE_AT) + "%";
    gate.appendChild(th);

    var mark = el("div", "edgeline");
    mark.style.left = pct(row.edge) + "%";
    gate.appendChild(mark);

    wrap.appendChild(gate);

    var col = el("div", "gate-col");
    col.appendChild(el("span", "edge " + (row.edge >= 0 ? "pos" : "neg"),
                       fmtEdge(row.edge)));
    var badge = el("span", "badge " + (row.edge >= GATE_AT ? "qualify" : "pass"),
                   row.edge >= GATE_AT ? "qualifies" : "pass");
    col.appendChild(badge);
    wrap.appendChild(col);
    return wrap;
  }

  function renderGates(host, rows) {
    if (!host) return;
    host.innerHTML = "";
    for (var i = 0; i < rows.length; i++) host.appendChild(gateRow(rows[i]));
  }

  /* ---------- spike chart ---------- */
  function renderSpikes(host, rows, legend) {
    if (!host) return;
    host.innerHTML = "";
    var max = 0;
    rows.forEach(function (r) { max = Math.max(max, r.one_sided, r.two_sided); });
    max = max * 1.15 || 1;
    rows.forEach(function (r) {
      var spike = el("div", "spike");
      var bars = el("div", "bars");
      [["one", r.one_sided], ["two", r.two_sided]].forEach(function (pair) {
        var b = el("div", "b " + pair[0]);
        b.style.height = (pair[1] / max) * 100 + "%";
        b.title = pair[1].toFixed(2) + "%";
        bars.appendChild(b);
      });
      spike.appendChild(bars);
      spike.appendChild(el("div", "val", r.one_sided.toFixed(1) + " / " + r.two_sided.toFixed(1)));
      spike.appendChild(el("div", "k", r.key));
      host.appendChild(spike);
    });
    if (legend) {
      legend.textContent = "Bars are % of games landing on the key. " +
        "Every key measured on " + rows.reduce(function (a, r) { return a + r.n; }, 0) +
        " games split across the seven keys (n per key in the table above).";
    }
  }

  /* ---------- tables ---------- */
  function renderTonight(host, t) {
    if (!host) return;
    var table = el("table");
    var cap = el("caption", null, "NZ TAB " + t.swept + " — priced against the " +
                "US no-vig median. Gate is +4%.");
    table.appendChild(cap);
    var thead = el("thead"), tr = el("tr");
    [["Market", ""], ["Selection", ""], ["TAB", "n"], ["US fair", "n"],
     ["Edge", "n"], [""]].forEach(function (h) {
      var th = el("th", h[1], h[0]);
      tr.appendChild(th);
    });
    thead.appendChild(tr);
    table.appendChild(thead);
    var tb = el("tbody");
    t.markets.forEach(function (m) {
      var r = el("tr");
      r.appendChild(el("td", null, m.market));
      r.appendChild(el("td", null, m.side));
      r.appendChild(el("td", "n", m.tab.toFixed(2)));
      r.appendChild(el("td", "n", m.fair.toFixed(3)));
      r.appendChild(el("td", "n " + (m.edge_pct >= 4 ? "pos" : "neg"), fmtEdge(m.edge_pct)));
      var verdict = el("td", null, m.edge_pct >= 4 ? "qualifies" : "pass");
      verdict.style.fontFamily = "var(--mono)";
      verdict.style.fontSize = "0.72rem";
      verdict.style.textTransform = "uppercase";
      verdict.style.color = "var(--fail)";
      r.appendChild(verdict);
      tb.appendChild(r);
    });
    table.appendChild(tb);
    host.innerHTML = "";
    host.appendChild(table);

    var gates = document.getElementById("tonightGates");
    renderGates(gates, t.markets.map(function (m) {
      return { side: m.side, sub: m.market, edge: m.edge_pct };
    }));
  }

  function renderEdges(host, sides, summary) {
    if (!host) return;
    var table = el("table");
    table.appendChild(el("caption", null,
      "All " + sides.length + " sides on the Week 1 board, best first. " +
      "Two de-vig methods, same prices — the method moves every edge, so it has to be agreed on."));
    var thead = el("thead"), tr = el("tr");
    [["Game", ""], ["Kickoff (NZ)", ""], ["Side", ""], ["TAB", "n"],
     ["Fair (proportional)", "n"], ["Edge", "n"], ["Fair (power)", "n"], ["Edge", "n"]]
      .forEach(function (h) { tr.appendChild(el("th", h[1], h[0])); });
    thead.appendChild(tr);
    table.appendChild(thead);
    var tb = el("tbody");
    sides.forEach(function (s) {
      var r = el("tr");
      if (Math.max(s.edge_prop, s.edge_power) >= 4) r.className = "flagged";
      r.appendChild(el("td", null, s.game));
      r.appendChild(el("td", null, s.kickoff.replace(/^\w+ /, "")));
      r.appendChild(el("td", null, s.team));
      r.appendChild(el("td", "n", s.tab.toFixed(2)));
      r.appendChild(el("td", "n", s.fair_prop.toFixed(3)));
      r.appendChild(el("td", "n " + (s.edge_prop >= 0 ? "pos" : "neg"), fmtEdge(s.edge_prop)));
      r.appendChild(el("td", "n", s.fair_power.toFixed(3)));
      r.appendChild(el("td", "n " + (s.edge_power >= 0 ? "pos" : "neg"), fmtEdge(s.edge_power)));
      tb.appendChild(r);
    });
    table.appendChild(tb);
    host.innerHTML = "";
    host.appendChild(table);
  }

  function renderKeyTable(host, kn) {
    if (!host) return;
    var table = el("table");
    table.appendChild(el("caption", null, kn.source));
    var thead = el("thead"), tr = el("tr");
    [["Key", "n"], ["Games", "n"], ["Favourite by k (decisive)", "n"],
     ["Either team by k", "n"], ["Half point worth", "n"], ["Doc said", "n"]]
      .forEach(function (h) { tr.appendChild(el("th", h[1], h[0])); });
    thead.appendChild(tr);
    table.appendChild(thead);
    var tb = el("tbody");
    kn.rows.forEach(function (k) {
      var r = el("tr");
      r.appendChild(el("td", "n", k.key));
      r.appendChild(el("td", "n", k.n));
      r.appendChild(el("td", "n " + (k.one_sided >= 8 ? "pos" : ""), k.one_sided.toFixed(2) + "%"));
      var td2 = el("td", "n", k.two_sided.toFixed(2) + "%");
      td2.style.color = "var(--leather)";
      td2.style.fontWeight = "600";
      r.appendChild(td2);
      r.appendChild(el("td", "n", k.value_loss_push.toFixed(1) + "–" +
                              k.value_push_win.toFixed(1) + "%"));
      r.appendChild(el("td", "n", k.doc_said.toFixed(1) + "%"));
      tb.appendChild(r);
    });
    table.appendChild(tb);
    host.innerHTML = "";
    host.appendChild(table);
  }

  /* ---------- boot ---------- */
  document.addEventListener("DOMContentLoaded", function () {
    var url = "assets/data/week01.json";
    fetch(url, { cache: "no-store" })
      .then(function (r) { if (!r.ok) throw new Error("HTTP " + r.status); return r.json(); })
      .then(function (d) {
        renderTonight(document.getElementById("tonightTable"), d.tonight);
        renderEdges(document.getElementById("edgesTable"), d.sides, d.summary);
        renderKeyTable(document.getElementById("keyTable"), d.key_numbers);
        renderSpikes(document.getElementById("spikes"), d.key_numbers.rows,
                     document.getElementById("spikeLegend"));
        var s = document.getElementById("summaryLine");
        if (s) {
          s.textContent = d.summary.sides_priced + " sides priced across " +
            d.summary.games_priced + " games. Sides at or past the +4% gate: " +
            d.summary.qualifying_prop + " under proportional de-vig, " +
            d.summary.qualifying_power + " under the power method.";
        }
      })
      .catch(function (e) {
        var hosts = ["tonightTable", "edgesTable", "keyTable"];
        hosts.forEach(function (id) {
          var h = document.getElementById(id);
          if (h) h.textContent = "Data module failed to load (" + e.message +
            "). Open the site over http:// rather than file://.";
        });
      });
  });
})();
