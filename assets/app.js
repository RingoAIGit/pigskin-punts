    function legacyCopy(text, done) {
      var ta = document.createElement("textarea");
      ta.value = text;
      ta.setAttribute("readonly", "");
      ta.style.position = "fixed";
      ta.style.top = "-1000px";
      document.body.appendChild(ta);
      ta.select();
      try { ta.setSelectionRange(0, ta.value.length); } catch (e) {}
      var ok = false;
      try { ok = document.execCommand("copy"); } catch (e) { ok = false; }
      document.body.removeChild(ta);
      if (ok) done();
      else msg.textContent = "Clipboard isn't available here — select the line above and copy it by hand.";
    }
    function copyLine(extra) {
      if (!current) current = build();
      var text = current.line;
      function done() {
        msg.textContent = extra || "Copied. Paste it anywhere Ringo will see it — Discord is quickest.";
      }
      if (navigator.clipboard && navigator.clipboard.writeText) {
        navigator.clipboard.writeText(text).then(done).catch(function () {
          legacyCopy(text, done);
        });
      } else {
        legacyCopy(text, done);
      }
    }
